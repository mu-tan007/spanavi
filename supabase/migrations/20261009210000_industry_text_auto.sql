-- 業種を文から決める規則の直し（2026-10-09 むー様「残りも全て進めて」）
-- 「自動車解体」の「解体」を土木工事と読んで、自動車関連の会社が「土木」になっていた。
-- 自動車の解体・中古部品・リサイクルパーツ・中古車・整備は先に「自動車整備・販売」で拾い、「解体」は建設の言い方のときだけ土木にする
create or replace function public.industry_group_from_text(t text)
returns text language sql immutable as $$
  select case
    when t is null or btrim(t) = '' then null
    when t ~ '自動車解体|自動車部品|中古部品|中古自動車|自動車中古|リサイクルパーツ|リビルト|廃車|自動車整備|自動車販売|自動車修理|車検|中古車|カー用品|新車|自動車リサイクル|車両リサイクル' then '自動車整備・販売'
    when t ~ '電気工事|電気設備|電気通信工事|電気配線' then '電気工事'
    when t ~ '管工事|給排水|衛生設備|空調|冷暖房|水道工事|配管' then '管工事'
    when t ~ '土木|舗装|とび|土工|しゅんせつ|浚渫|解体工事|建物解体|構造物解体|家屋解体|造園' then '土木'
    when t ~ '内装|塗装|防水|鉄骨|左官|板金工事|屋根|サッシ|建具|設計事務所|建築設計|測量' then '専門工事'
    when t ~ '総合工事|建築工事|工務店|リフォーム|住宅建築|建設' then '建築工事'
    when t ~ '酒造|清酒|焼酎|醸造|製茶|茶' then '酒造・製茶'
    when t ~ '食品|菓子|パン|麺|めん|水産加工|惣菜|食肉|乳製品|調味料|豆腐|飲料' and t ~ '製造|加工' then '食品製造'
    when t ~ '運送|運輸|物流|倉庫|配送|貨物|トラック' then '運送・物流'
    when t ~ 'ソフトウェア|システム開発|受託開発|SES|情報処理|IT|ＩＴ|Web|ＷＥＢ|アプリ' then 'IT'
    when t ~ '派遣|人材紹介|職業紹介|人材' then '人材'
    when t ~ 'ビルメンテナンス|建物管理|清掃|ビル管理' then 'ビルメンテナンス'
    when t ~ '警備' then '警備'
    when t ~ '産業廃棄物|廃棄物|リサイクル|ごみ|スクラップ|鉄屑|解体' then '産業廃棄物'
    when t ~ '調剤|薬局' then '調剤薬局'
    when t ~ '歯科' then '歯科'
    when t ~ '介護|福祉|デイサービス|老人ホーム|障害者|保育' then '介護・福祉'
    when t ~ '病院|診療所|クリニック|医療' then '医療'
    when t ~ '不動産|賃貸|仲介|マンション管理' then '不動産'
    when t ~ 'ガソリンスタンド|石油販売|燃料' then 'ガソリンスタンド'
    when t ~ '保険代理' then '保険代理店'
    when t ~ '学校|学習塾|塾|教室|教育' then '教育・学習支援'
    when t ~ 'ホテル|旅館|宿泊|民泊' then '宿泊'
    when t ~ '飲食|レストラン|居酒屋|小売|スーパー|販売店|ショップ' then '飲食・小売'
    when t ~ '卸売|卸' then '卸売'
    when t ~ '製造|製作所|加工|工業|金型|プレス|機械' then '製造'
    when t ~ 'コンサル|設計|デザイン|広告|検査' then '専門サービス'
    else null end
$$;
