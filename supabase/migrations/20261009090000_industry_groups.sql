-- 業種を付ける（まだ付けていない会社だけ。p_limit 件ずつ）
create or replace function public.assign_industry(p_limit int default 50000)
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  create temp table if not exists _todo on commit drop as
  select i.id, i.list_id, regexp_replace(coalesce(i.phone,''),'\D','','g') ph, i.business, l.industry list_ind
  from call_list_items i join call_lists l on l.id = i.list_id
  where i.industry_checked_at is null
  limit p_limit;
  create temp table if not exists _hit on commit drop as
  select distinct on (t.id) t.id, mp.grp, nullif(cm.industry_sub,'') sub
  from _todo t
  join company_master cm on length(t.ph) >= 9 and cm.phone is not null and regexp_replace(cm.phone,'\D','','g') = t.ph
  join industry_group_map mp on mp.tsr_major = coalesce(cm.industry_major,'') and mp.tsr_sub = coalesce(cm.industry_sub,'');
  update call_list_items i set
    industry_group = coalesce(h.grp, public.industry_group_from_text(t.business), public.industry_group_from_text(t.list_ind)),
    -- 細かい業種名：業種を絞ったリストならリストの業種、それ以外は細分類
    industry_label = case when t.list_ind is not null and t.list_ind !~ '全業種|^\s*$' then t.list_ind else coalesce(h.sub, t.list_ind) end,
    industry_source = case when h.grp is not null then 'tsr' when public.industry_group_from_text(t.business) is not null then 'text'
                           when public.industry_group_from_text(t.list_ind) is not null then 'list' else null end,
    industry_checked_at = now()
  from _todo t left join _hit h on h.id = t.id
  where i.id = t.id;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- 業種×曜日×時間帯のキーマン接続率（全架電。毎日20時に出し直す）
create table if not exists public.industry_connect_rates (
  grp text not null, dow int not null, hour int not null, calls int not null, keyman int not null, rate numeric not null,
  updated_at timestamptz not null default now(), primary key (grp, dow, hour)
);
alter table public.industry_connect_rates enable row level security;
drop policy if exists industry_connect_rates_read on public.industry_connect_rates;
create policy industry_connect_rates_read on public.industry_connect_rates for select to authenticated using (true);
-- dow 0 = すべての曜日、hour -1 = すべての時間
create or replace function public.refresh_industry_connect_rates()
returns void language plpgsql security definer set search_path = public as $$
begin
  create temp table if not exists _c on commit drop as
  select i.industry_group g, extract(isodow from r.called_at at time zone 'Asia/Tokyo')::int dow, extract(hour from r.called_at at time zone 'Asia/Tokyo')::int hr,
         (r.status in ('キーマン断り','キーマン再コール','アポ獲得')) km
  from call_records r join call_list_items i on i.id = r.item_id
  where r.org_id = 'a0000000-0000-0000-0000-000000000001' and r.status <> '除外' and i.industry_group is not null;
  delete from industry_connect_rates;
  insert into industry_connect_rates (grp, dow, hour, calls, keyman, rate)
  select g, dow, hr, count(*), count(*) filter (where km), round(count(*) filter (where km)::numeric / count(*), 4) from _c group by g, dow, hr
  union all select g, 0, hr, count(*), count(*) filter (where km), round(count(*) filter (where km)::numeric / count(*), 4) from _c group by g, hr
  union all select g, dow, -1, count(*), count(*) filter (where km), round(count(*) filter (where km)::numeric / count(*), 4) from _c group by g, dow
  union all select g, 0, -1, count(*), count(*) filter (where km), round(count(*) filter (where km)::numeric / count(*), 4) from _c group by g;
end;
$$;
-- 毎日20時（アポ率と同じ時刻）に、新しい会社に業種を付けてから出し直す
