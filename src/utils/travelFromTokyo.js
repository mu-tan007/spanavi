const PREF_RE = /^(東京都|北海道|(?:京都|大阪)府|.{2,3}県)/;

/** 住所から { pref, city, hours, means } を返す。都道府県が読めなければ null */
export function travelFromTokyo(address) {
  const a = String(address || '').replace(/^〒?\s*\d{3}-?\d{4}\s*/, '').trim();
  const m = a.match(PREF_RE);
  if (!m || !HOURS[m[1]]) return null;
  const pref = m[1];
  const rest = a.slice(pref.length);
  const city = (rest.match(/^(.+?[市区町村])/) || [])[1] || '';
  let [hours, means] = HOURS[pref];
  // 東京都でも多摩・島しょは区部より遠い
  if (pref === '東京都' && city && !/区$/.test(city)) hours = /島|大島|八丈|三宅/.test(city) ? 4 : 1;
  return { pref, city, hours, means };
}

/** 画面に出す1行（例：「大阪府大阪市 ・ 東京から片道 約3時間（新幹線）」） */
export function travelLabel(address) {
  const t = travelFromTokyo(address);
  if (!t) return null;
  const h = Number.isInteger(t.hours) ? `${t.hours}時間` : `${Math.floor(t.hours) ? Math.floor(t.hours) + '時間' : ''}30分`;
  return `${t.pref}${t.city} ・ 東京から片道 約${h}（${t.means}）`;
}
